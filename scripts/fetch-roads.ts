/**
 * Fetches real road geometry between every pair of demo places from the public
 * OSRM router, once, and writes server/data/roads.ts. Run with:
 *   node scripts/fetch-roads.ts
 * The OSRM demo server allows about one request a second, so this takes ~10 minutes.
 */
import { writeFileSync } from 'node:fs';
import { PLACES } from '../server/data/network.ts';

type Pt = [number, number];

function simplify(pts: Pt[], tol: number): Pt[] {
  if (pts.length < 3) return pts;
  const keep = new Uint8Array(pts.length);
  keep[0] = keep[pts.length - 1] = 1;
  const stack: [number, number][] = [[0, pts.length - 1]];
  while (stack.length) {
    const [a, b] = stack.pop()!;
    const [x1, y1] = pts[a];
    const [x2, y2] = pts[b];
    const dx = x2 - x1, dy = y2 - y1;
    const len = Math.hypot(dx, dy) || 1e-12;
    let max = 0, idx = -1;
    for (let i = a + 1; i < b; i++) {
      const d = Math.abs(dy * pts[i][0] - dx * pts[i][1] + x2 * y1 - y2 * x1) / len;
      if (d > max) { max = d; idx = i; }
    }
    if (max > tol && idx > 0) {
      keep[idx] = 1;
      stack.push([a, idx], [idx, b]);
    }
  }
  return pts.filter((_, i) => keep[i]);
}

/** Google's encoded polyline format, 5-decimal precision, [lng, lat] input. */
function encode(pts: Pt[]) {
  let out = '', pLat = 0, pLng = 0;
  const enc = (v: number) => {
    let n = v < 0 ? ~(v << 1) : v << 1;
    while (n >= 0x20) { out += String.fromCharCode((0x20 | (n & 0x1f)) + 63); n >>= 5; }
    out += String.fromCharCode(n + 63);
  };
  for (const [lng, lat] of pts) {
    const la = Math.round(lat * 1e5), ln = Math.round(lng * 1e5);
    enc(la - pLat); enc(ln - pLng);
    pLat = la; pLng = ln;
  }
  return out;
}

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

async function route(a: Pt, b: Pt) {
  const url = `https://router.project-osrm.org/route/v1/driving/${a[0]},${a[1]};${b[0]},${b[1]}?overview=full&geometries=geojson`;
  for (let attempt = 0; attempt < 4; attempt++) {
    try {
      const res = await fetch(url, { headers: { 'user-agent': 'hop-demo-build/1.0' } });
      if (res.ok) {
        const j = await res.json();
        const r = j.routes?.[0];
        if (r) return { km: r.distance / 1000, min: r.duration / 60, coords: r.geometry.coordinates as Pt[] };
      }
    } catch { /* retry */ }
    await sleep(2000 * (attempt + 1));
  }
  return null;
}

const out: Record<string, [number, number, string]> = {};
const pairs: [number, number][] = [];
for (let i = 0; i < PLACES.length; i++) for (let j = i + 1; j < PLACES.length; j++) pairs.push([i, j]);

let n = 0;
for (const [i, j] of pairs) {
  const a = PLACES[i], b = PLACES[j];
  const r = await route(a.lngLat, b.lngLat);
  n++;
  if (r) {
    const pts = simplify(r.coords, 0.00008);
    out[`${a.id}|${b.id}`] = [Math.round(r.km * 10) / 10, Math.round(r.min * 10) / 10, encode(pts)];
  }
  if (n % 25 === 0) console.log(`${n}/${pairs.length}`);
  await sleep(1050);
}

const body = `// Generated by scripts/fetch-roads.ts from OSRM (© OpenStreetMap contributors). Do not edit.\n// Key "a|b" (ids in PLACES order): [road km, free-flow minutes, encoded polyline a→b]\nexport const ROADS: Record<string, [number, number, string]> = ${JSON.stringify(out)};\n`;
writeFileSync(new URL('../server/data/roads.ts', import.meta.url), body);
console.log(`done: ${Object.keys(out).length}/${pairs.length} pairs`);
